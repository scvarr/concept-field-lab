def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def act(store, action, **data):
    return store.mutate(action, data, store.read()["revision"])["result"]


def build(db, output):
    if not db.resolve().is_relative_to(ROOT / "local-data/nut-k003"):
        raise ValueError("Только отдельная база внутри local-data/nut-k003")
    if (output / "nut.json").exists():
        raise ValueError("Существующий итог не перезаписывается; выберите другой output")
    store = Store(db)
    if store.read()["state"]["studies"]:
        raise ValueError("Нужна новая пустая база; пользовательские данные не изменяются")
    inventory = json.loads((DATA / "inventory.json").read_text(encoding="utf-8"))
    made = act(store, "create_study", title="Гайка — K003", label="гайка", description="Независимое постоянное раскрытие крепёжной детали; ручные предложения снизу вверх, не полное определение, не сцена монтажа. K001/K002 и полотно не использованы.")
    sid = made["studyId"]
    ids = {"root": made["nodeId"]}
    act(store, "edit_node", studyId=sid, nodeId=ids["root"], label="гайка", kind="концептуальный вход", structure="concept", notes="Вход в структуру крепёжной детали с внутренним резьбовым сопряжением. Слово отдельно в словаре; корень не полная дефиниция и не экземпляр.", source=SOURCE)
    for candidate in inventory["candidates"]:
        key = int(candidate["id"][1:])
        ids[key] = act(store, "add_node", studyId=sid, label=candidate["text"], notes="Предварительный смысловой кандидат, не выбранная структура и не доказанное свойство каждой гайки.", source=SOURCE)["nodeId"]
    write(output / "ungrouped.json", graph_export(store, sid))
    selected = {key for key, _, _ in ROWS}
    for key in range(1, len(inventory["candidates"]) + 1):
        if key not in selected:
            act(store, "delete_node", studyId=sid, nodeId=ids[key])
    for key, _, notes in ROWS:
        act(store, "edit_node", studyId=sid, nodeId=ids[key], label=inventory["candidates"][key-1]["text"], notes=notes, source=SOURCE)
    extra = {
        "body": ("исполнение тела", "Общность материала, поверхностного слоя и возможной вставки обнаружена после сбора. Это конструктивная область, не универсальная классификация характеристик."),
        "support_friction": ("трение опорного контакта", "Сопротивление относительному скольжению в опорной области; не численный коэффициент и не условие всех соединений."),
        "thread_friction": ("трение резьбового контакта", "Сопротивление относительному скольжению в резьбовой области. Не слито с опорным контактом по общему слову «трение»."),
        "fit": ("", "Осмысленный совместный состав геометрических позиций резьбового сопряжения: профиль, номинальный / средний диаметры, шаг, направление, допуск. Не исполняет проверку совместимости и не доказывает её достаточность."),
    }
    for key, (label, notes) in extra.items():
        ids[key] = act(store, "add_node", studyId=sid, label=label, structure="combination" if key == "fit" else "concept", notes=notes, source=SOURCE)["nodeId"]
    routes = [(parent, key, notes) for key, parent, notes in ROWS]
    routes += [("root", "body", extra["body"][1]), (8, "support_friction", extra["support_friction"][1]), (28, "thread_friction", extra["thread_friction"][1]), (1, "fit", extra["fit"][1])]
    edge_audit = []
    for parent, key, notes in routes:
        act(store, "add_edge", studyId=sid, **{"from": ids[parent], "to": ids[key], "type": "", "role": "component" if parent == "fit" else "relation", "componentRole": "", "notes": notes})
        edge = next(s for s in store.read()["state"]["studies"] if s["id"] == sid)["edges"][-1]
        edge_audit.append({"id": edge["id"], "fromKey": str(parent), "toKey": str(key), "function": notes})
    for target, text in (("root", "гайка"), ("root", "резьбовая гайка"), ("fit", "геометрия резьбового сопряжения")):
        act(store, "add_designation", studyId=sid, target=ids[target], text=text, source=SOURCE, notes="Внешнее обозначение выбранной структуры, не отдельный концепт и не утверждение эквивалентности с другими исследованиями.")
    # Chosen visual positions only, recorded through the normal journal.
    children = {key: [] for key in ["root", *selected, *extra]}
    for parent, key, _ in routes:
        children[parent].append(key)
    cursor = 0

    def position(key, depth):
        nonlocal cursor
        if children[key]:
            ys = [position(child, depth+1) for child in children[key]]
            y = (min(ys) + max(ys)) / 2
        else:
            y = cursor * 90
            cursor += 1
        act(store, "position", studyId=sid, nodeId=ids[key], x=depth*300, y=y)
        return y

    position("root", 0)
    doc = graph_export(store, sid)
    validate(doc["state"])
    assert not doc["state"]["matches"] and not doc["state"]["studies"][0].get("accumulation")
    decisions = []
    for candidate in inventory["candidates"]:
        key = int(candidate["id"][1:])
        if key in selected:
            status, reason, targets = "selected", next(notes for n, _, notes in ROWS if n == key), [ids[key]]
        elif key == 17:
            status, reason, targets = "split", "Общее слово разделено по опорному и резьбовому контакту, без утверждения тождества.", [ids["support_friction"], ids["thread_friction"]]
        elif key == 56:
            status, reason, targets = "composition", extra["fit"][1], [ids["fit"]]
        else:
            status, reason, targets = "excluded", EXCLUSIONS[key], []
        decisions.append({**candidate, "status": status, "reason": reason, "targetIds": targets})
    nodes = doc["state"]["studies"][0]["nodes"]
    audit = {"experiment": "K003", "studyId": sid, "rootId": ids["root"], "revision": store.read()["revision"], "nodeKeys": {str(k): v for k, v in ids.items() if k in selected or k in extra or k == "root"}, "decisions": decisions, "edges": edge_audit, "counts": {"concepts": sum(n.get("structure", "concept") != "combination" for n in nodes), "alpha": sum(n.get("structure") == "combination" for n in nodes), "edges": len(edge_audit)}, "limits": ["Не полный набор гаек / свойств; источники дают контрпримеры, не онтологию.", "Альтернативность, необходимость, совместимость и допустимые нагрузки не исполняются моделью графа.", "Граница гайки, резьбовой втулки и сборочной единицы не доказана.", "Сложные листья не объявлены атомами; нет сцен, значений экземпляра или тождества с K001/K002."]}
    write(output / "structure-audit.json", audit)
    write(output / "nut.json", doc)
    print(json.dumps({"db": str(db), "graph": str(output / "nut.json"), **audit["counts"], "revision": audit["revision"]}, ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    build(args.db, args.output)
