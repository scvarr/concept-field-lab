def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def act(store, action, **data):
    return store.mutate(action, data, store.read()["revision"])["result"]


def current(store):
    return next(s for s in store.read()["state"]["studies"] if s["title"] == "Передача — K002")


def inventory(store):
    if store.read()["state"]["studies"]:
        raise ValueError("Первичный сбор — только в пустой собственной базе")
    rows = [line.split("|", 1) for line in RAW.strip().splitlines()]
    assert len({label for label, _ in rows}) == len(rows)
    write(ARTIFACTS / "inventory.json", {
        "experiment": "K002", "date": "2026-10-12", "stage": "Негруппированный сбор до структуры",
        "status": "Кандидаты конечных элементов этого прохода; элементарность не доказана",
        "source": SOURCE, "elements": [{"label": a, "question": b} for a, b in rows]})
    made = act(store, "create_study", title="Передача — K002", label="передача",
               description="Негруппированный первичный сбор. Связи и категории пока не назначены.")
    sid = made["studyId"]
    act(store, "edit_node", studyId=sid, nodeId=made["nodeId"], label="передача", kind="",
        source=SOURCE, notes="Вход для различения чтений многозначного слова; не общий семантический род.")
    for label, question in rows:
        act(store, "add_node", studyId=sid, label=label, kind="", source=SOURCE, notes=question)
    validate(store.read()["state"])
    write(ARTIFACTS / "ungrouped.json", graph_export(store, sid))
    print(f"K002.1: {len(rows)} кандидата; 0 связей; версия {store.read()['revision']}")


